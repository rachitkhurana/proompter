// Generates src/ui/fonts/fonts-data.ts and licenses/Geist-OFL.txt from the Fontsource packages.
//
//   pnpm add -DE @fontsource-variable/geist@5.3.0 @fontsource-variable/geist-mono@5.3.0
//   node src/ui/fonts/build-fonts.mjs
//
// Fontsource already ships one woff2 per unicode subset, so the "latin" files are the latin subset of
// the variable fonts (weight axis 100-900). No subsetting tool (pyftsubset etc.) is needed.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "..");

const sources = [
  { pkg: "@fontsource-variable/geist", file: "geist-latin-wght-normal.woff2", name: "GEIST_SANS_WOFF2_BASE64" },
  { pkg: "@fontsource-variable/geist-mono", file: "geist-mono-latin-wght-normal.woff2", name: "GEIST_MONO_WOFF2_BASE64" },
];

let out = `// @generated by src/ui/fonts/build-fonts.mjs. Do not edit.
// Geist and Geist Mono variable woff2, latin subset, base64. SIL OFL 1.1, see licenses/Geist-OFL.txt.
// Imported only by ./fonts.ts, which lives in the lazily loaded UI chunk.
`;
const licenses = [];

for (const { pkg, file, name } of sources) {
  const dir = join(root, "node_modules", pkg);
  const path = join(dir, "files", file);
  if (!existsSync(path)) {
    const have = existsSync(join(dir, "files")) ? readdirSync(join(dir, "files")).filter((f) => f.includes("latin")) : [];
    throw new Error(`Missing ${path}. Install ${pkg} first. Latin files found: ${have.join(", ") || "none"}`);
  }
  const bytes = readFileSync(path);
  console.log(`${name}: ${(bytes.length / 1024).toFixed(1)} KB woff2`);
  out += `export const ${name} = ${JSON.stringify(bytes.toString("base64"))};\n`;
  const licensePath = join(dir, "LICENSE");
  if (existsSync(licensePath)) licenses.push(`===== ${pkg} =====\n\n${readFileSync(licensePath, "utf8").trim()}\n`);
}

writeFileSync(join(root, "src", "ui", "fonts", "fonts-data.ts"), out);

if (licenses.length === sources.length) {
  mkdirSync(join(root, "licenses"), { recursive: true });
  writeFileSync(join(root, "licenses", "Geist-OFL.txt"), licenses.join("\n"));
  console.log("wrote licenses/Geist-OFL.txt from the packages' LICENSE files");
} else {
  console.warn("A package had no LICENSE file; licenses/Geist-OFL.txt left as is. Check it by hand.");
}
